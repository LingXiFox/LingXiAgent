import Foundation
import LingXiProtocol

/// Standardized action token for agent trajectory prediction and branch forecasting.
public enum ActionToken: Hashable, Sendable, Codable, CustomStringConvertible {
    case tool(name: String)
    case directAnswer
    case askQuestion
    case subagent(task: String)
    case finish
    case userInterrupt
    case cancel

    public var description: String {
        switch self {
        case let .tool(name):
            return "tool:\(name)"
        case .directAnswer:
            return "directAnswer"
        case .askQuestion:
            return "askQuestion"
        case let .subagent(task):
            return "subagent:\(task)"
        case .finish:
            return "finish"
        case .userInterrupt:
            return "userInterrupt"
        case .cancel:
            return "cancel"
        }
    }
}

/// Advisory-only prediction result generated by the Branch Prediction Fabric.
public struct PredictionResult: Sendable, Equatable {
    public struct Candidate: Sendable, Equatable {
        public let token: ActionToken
        public let probability: Double
        public let count: Int

        public init(token: ActionToken, probability: Double, count: Int = 0) {
            self.token = token
            self.probability = probability
            self.count = count
        }
    }

    public let top1: ActionToken?
    public let topConfidence: Double
    public let support: Int
    public let matchedOrder: Int
    public let candidates: [Candidate]

    public init(
        top1: ActionToken?,
        topConfidence: Double,
        support: Int = 0,
        matchedOrder: Int,
        candidates: [Candidate]
    ) {
        self.top1 = top1
        self.topConfidence = topConfidence
        self.support = support
        self.matchedOrder = matchedOrder
        self.candidates = candidates
    }
}

/// Offline evaluation metrics for branch forecasting calibration and accuracy.
public struct PredictorEvaluationMetrics: Sendable, Equatable {
    public let totalSamples: Int
    public let top1Accuracy: Double
    public let top3Accuracy: Double
    public let coverage: Double
    public let brierScore: Double
    public let expectedCalibrationError: Double

    public init(
        totalSamples: Int,
        top1Accuracy: Double,
        top3Accuracy: Double,
        coverage: Double,
        brierScore: Double,
        expectedCalibrationError: Double
    ) {
        self.totalSamples = totalSamples
        self.top1Accuracy = top1Accuracy
        self.top3Accuracy = top3Accuracy
        self.coverage = coverage
        self.brierScore = brierScore
        self.expectedCalibrationError = expectedCalibrationError
    }
}

/// Variable-Order Markov Model (VOMM) predictor with n-gram back-off.
/// Invariant: Strictly advisory-only. Does not interfere with runtime agent execution.
public final class VariableOrderMarkovPredictor: @unchecked Sendable {
    public let maxOrder: Int
    private let lock = NSLock()
    // Context tuple key (comma-separated tokens) -> (NextToken -> Count)
    private var transitionCounts: [String: [ActionToken: Int]] = [:]
    private var priorCounts: [ActionToken: Int] = [:]
    private var totalPriors: Int = 0

    public init(maxOrder: Int = 3) {
        self.maxOrder = max(1, maxOrder)
    }

    private func contextKey(_ tokens: [ActionToken]) -> String {
        tokens.map { token in
            let desc = token.description
            return "\(desc.utf8.count):\(desc)"
        }.joined(separator: ";")
    }

    /// Train offline with multiple standardized action sequences.
    public func train(sequences: [[ActionToken]]) {
        lock.lock()
        defer { lock.unlock() }

        for seq in sequences {
            guard !seq.isEmpty else { continue }
            for i in 0..<seq.count {
                let target = seq[i]
                priorCounts[target, default: 0] += 1
                totalPriors += 1

                let maxOrderForStep = min(i, maxOrder)
                if maxOrderForStep >= 1 {
                    for order in 1...maxOrderForStep {
                        let ctxSlice = Array(seq[(i - order)..<i])
                        let key = contextKey(ctxSlice)
                        if transitionCounts[key] == nil {
                            transitionCounts[key] = [:]
                        }
                        transitionCounts[key]![target, default: 0] += 1
                    }
                }
            }
        }
    }

    /// Predict next action given recent history with back-off mechanism.
    public func predictNext(context: [ActionToken]) -> PredictionResult {
        lock.lock()
        defer { lock.unlock() }

        guard totalPriors > 0 else {
            return PredictionResult(top1: nil, topConfidence: 0.0, support: 0, matchedOrder: 0, candidates: [])
        }

        // Try higher order down to 1
        let effectiveMax = min(context.count, maxOrder)
        for order in stride(from: effectiveMax, through: 1, by: -1) {
            let ctxSlice = Array(context.suffix(order))
            let key = contextKey(ctxSlice)
            if let counts = transitionCounts[key], !counts.isEmpty {
                let total = Double(counts.values.reduce(0, +))
                let totalCount = counts.values.reduce(0, +)
                if total > 0 {
                    let sorted = counts.map { (token: $0.key, prob: Double($0.value) / total, count: $0.value) }
                        .sorted {
                            if abs($0.prob - $1.prob) > 1e-9 {
                                return $0.prob > $1.prob
                            }
                            return $0.token.description < $1.token.description
                        }
                    let candidates = sorted.map { PredictionResult.Candidate(token: $0.token, probability: $0.prob, count: $0.count) }
                    return PredictionResult(
                        top1: candidates.first?.token,
                        topConfidence: candidates.first?.probability ?? 0.0,
                        support: totalCount,
                        matchedOrder: order,
                        candidates: candidates
                    )
                }
            }
        }

        // Fallback to order 0 (global prior distribution)
        let total = Double(totalPriors)
        let sorted = priorCounts.map { (token: $0.key, prob: Double($0.value) / total, count: $0.value) }
            .sorted {
                if abs($0.prob - $1.prob) > 1e-9 {
                    return $0.prob > $1.prob
                }
                return $0.token.description < $1.token.description
            }
        let candidates = sorted.map { PredictionResult.Candidate(token: $0.token, probability: $0.prob, count: $0.count) }
        return PredictionResult(
            top1: candidates.first?.token,
            topConfidence: candidates.first?.probability ?? 0.0,
            support: totalPriors,
            matchedOrder: 0,
            candidates: candidates
        )
    }

    /// Evaluate model on holdout test sequences and compute calibration and accuracy metrics.
    public func evaluate(testSequences: [[ActionToken]], numCalibrationBins: Int = 5) -> PredictorEvaluationMetrics {
        var totalSamples = 0
        var top1Hits = 0
        var top3Hits = 0
        var brierScoreSum = 0.0

        struct PredSample {
            let confidence: Double
            let hit: Bool
        }
        var samples: [PredSample] = []

        for seq in testSequences {
            guard seq.count >= 2 else { continue }
            for i in 1..<seq.count {
                let ctx = Array(seq[0..<i])
                let actual = seq[i]
                let pred = predictNext(context: ctx)

                guard let top1 = pred.top1 else { continue }
                totalSamples += 1

                let isTop1 = (top1 == actual)
                if isTop1 { top1Hits += 1 }

                let inTop3 = pred.candidates.prefix(3).contains { $0.token == actual }
                if inTop3 { top3Hits += 1 }

                // Brier score: sum of squared error across all probabilities
                var brier = 0.0
                var foundActual = false
                for cand in pred.candidates {
                    let target = (cand.token == actual) ? 1.0 : 0.0
                    if cand.token == actual { foundActual = true }
                    brier += pow(cand.probability - target, 2.0)
                }
                if !foundActual {
                    brier += 1.0 // Actual had 0.0 predicted probability
                }
                brierScoreSum += brier

                samples.append(PredSample(confidence: pred.topConfidence, hit: isTop1))
            }
        }

        guard totalSamples > 0 else {
            return PredictorEvaluationMetrics(
                totalSamples: 0,
                top1Accuracy: 0.0,
                top3Accuracy: 0.0,
                coverage: 0.0,
                brierScore: 0.0,
                expectedCalibrationError: 0.0
            )
        }

        let top1Acc = Double(top1Hits) / Double(totalSamples)
        let top3Acc = Double(top3Hits) / Double(totalSamples)
        let meanBrier = brierScoreSum / Double(totalSamples)

        // Expected Calibration Error (ECE)
        var ece = 0.0
        let binSize = 1.0 / Double(numCalibrationBins)
        for b in 0..<numCalibrationBins {
            let binStart = Double(b) * binSize
            let binEnd = Double(b + 1) * binSize
            let binSamples = samples.filter { $0.confidence >= binStart && ($0.confidence < binEnd || b == numCalibrationBins - 1) }
            guard !binSamples.isEmpty else { continue }
            let avgConfidence = binSamples.map(\.confidence).reduce(0, +) / Double(binSamples.count)
            let avgAccuracy = Double(binSamples.filter(\.hit).count) / Double(binSamples.count)
            let weight = Double(binSamples.count) / Double(totalSamples)
            ece += weight * abs(avgAccuracy - avgConfidence)
        }

        return PredictorEvaluationMetrics(
            totalSamples: totalSamples,
            top1Accuracy: top1Acc,
            top3Accuracy: top3Acc,
            coverage: 1.0,
            brierScore: meanBrier,
            expectedCalibrationError: ece
        )
    }
}

/// Extractor to parse SessionEventLog events into standardized action token sequences.
/// Invariant: Respects model decision order (toolRequested dispatch sequence) rather than runtime completion order.
public struct TrajectoryExtractor: Sendable {
    public init() {}

    public func extract(from events: [SessionEventEnvelope]) -> [ActionToken] {
        var tokens: [ActionToken] = []
        var seenCancelledRuns: Set<RunID> = []
        var seenCancelledTurns: Set<TurnID> = []

        for record in events {
            switch record.payload {
            case let .toolRequested(inv):
                tokens.append(.tool(name: inv.toolID.rawValue))
            case .assistantMessageCommitted:
                tokens.append(.directAnswer)
            case let .runCompleted(runID, terminalReason):
                if terminalReason == .userCancelled {
                    if !seenCancelledRuns.contains(runID) {
                        seenCancelledRuns.insert(runID)
                        tokens.append(.cancel)
                    }
                } else {
                    tokens.append(.finish)
                }
            case let .runCancelled(runID, _):
                if !seenCancelledRuns.contains(runID) {
                    seenCancelledRuns.insert(runID)
                    tokens.append(.cancel)
                }
            case let .turnCompleted(turnID, terminalReason):
                if terminalReason == .userCancelled {
                    if let runID = record.causal.runID {
                        if !seenCancelledRuns.contains(runID) {
                            seenCancelledRuns.insert(runID)
                            tokens.append(.cancel)
                        }
                    } else if !seenCancelledTurns.contains(turnID) {
                        seenCancelledTurns.insert(turnID)
                        tokens.append(.cancel)
                    }
                }
            default:
                break
            }
        }
        return tokens
    }

    /// Splits event log into isolated episode sequences divided by Run and terminal state boundaries.
    /// Invariant: Prevents falsely learning transitions across Run boundaries (e.g. preceding .finish -> subsequent .tool).
    public func extractEpisodes(from events: [SessionEventEnvelope]) -> [[ActionToken]] {
        var episodes: [[ActionToken]] = []
        var current: [ActionToken] = []
        var seenCancelledRuns: Set<RunID> = []

        for record in events {
            switch record.payload {
            case let .toolRequested(inv):
                current.append(.tool(name: inv.toolID.rawValue))
            case .assistantMessageCommitted:
                current.append(.directAnswer)
            case let .runCompleted(runID, terminalReason):
                if terminalReason == .userCancelled {
                    if !seenCancelledRuns.contains(runID) {
                        seenCancelledRuns.insert(runID)
                        current.append(.cancel)
                    }
                } else {
                    current.append(.finish)
                }
                if !current.isEmpty {
                    episodes.append(current)
                    current = []
                }
            case let .runCancelled(runID, _):
                if !seenCancelledRuns.contains(runID) {
                    seenCancelledRuns.insert(runID)
                    current.append(.cancel)
                }
                if !current.isEmpty {
                    episodes.append(current)
                    current = []
                }
            case .runFailed:
                current.append(.cancel)
                if !current.isEmpty {
                    episodes.append(current)
                    current = []
                }
            default:
                break
            }
        }

        if !current.isEmpty {
            episodes.append(current)
        }
        return episodes
    }
}

// MARK: - Prediction Snapshot Extension

extension PredictionResult {
    public func makeSnapshot(
        epoch: UInt64,
        sessionID: String,
        runID: String? = nil,
        isStale: Bool = false
    ) -> PredictionSnapshot {
        let dtos = candidates.map {
            PredictionSnapshot.CandidateDTO(action: $0.token.description, probability: $0.probability, count: $0.count)
        }
        return PredictionSnapshot(
            epoch: epoch,
            sessionID: sessionID,
            runID: runID,
            top1Action: top1?.description,
            topConfidence: topConfidence,
            support: support,
            matchedOrder: matchedOrder,
            candidates: dtos,
            mode: "shadow",
            isLowSupport: support < 3,
            isStale: isStale
        )
    }
}
